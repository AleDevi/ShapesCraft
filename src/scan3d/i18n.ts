export type Translate3d = (key: Key, vars?: Record<string, string | number>) => string;

export function translator3d(lang: Lang): Translate3d {
  const dict = lang === 'it' ? it : en;
  return (key, vars = {}) => dict[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
